-- DROP FUNCTION public.filter_assessments_by_domains(jsonb, _int4);

CREATE OR REPLACE FUNCTION public.filter_assessments_by_domains(mappeddata jsonb, domain_ids integer[])
 RETURNS TABLE(response jsonb)
 LANGUAGE plpgsql
 STABLE
AS $function$
declare
  assessment_row jsonb;
  answers integer[];
  domain_row record;
  matched_domains jsonb;
begin
  for assessment_row in
    select value
    from jsonb_array_elements(mappeddata) as t(value)
  loop
    answers := array(
      select value::integer
      from jsonb_array_elements_text(coalesce(assessment_row -> 'responses', '[]'::jsonb)) with ordinality as x(value, ord)
      order by ord
    );

    matched_domains := '[]'::jsonb;

    for domain_row in
      select id, name, question_indexes
      from public.assessment_domains
      where id = any(domain_ids)
      order by id
    loop
      if exists (
        select 1
        from unnest(domain_row.question_indexes) as q(question_index)
        where coalesce(answers[q.question_index + 1], 0) > 0
      ) then
        matched_domains := matched_domains || jsonb_build_array(
          jsonb_build_object('domain_name', domain_row.name)
        );
      end if;
    end loop;

    response := matched_domains;
    return next;
  end loop;
end;
$function$
;

