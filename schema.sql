-- DROP FUNCTION public.get_assessments_table(text, text, text, text, text);

CREATE OR REPLACE FUNCTION public.get_assessments_table(search_query text, selected_scenario_name text, selected_status_name text, page_size text, page_number text)
 RETURNS TABLE(total_count bigint, id bigint, created_at timestamp with time zone, user_id uuid, first_name text, middle_name text, last_name text, name_suffix text, student_number text, result_scenario text, counseling_status text)
 LANGUAGE sql
 STABLE
AS $function$
  with base as (
    select
      count(*) over () as total_count,
      ar.id,
      a.created_at,
      ar.user_id,
      pd.first_name,
      pd.middle_name,
      pd.last_name,
      pd.name_suffix,
      pd.student_number,
      s.name as result_scenario,
      coalesce(cs.name, '') as counseling_status
    from public.apriori_results ar
    join public.assessments a on a.id = ar.assessment_id
    join public.personal_details pd on pd.user_id = ar.user_id
    join public.assessment_scenarios s on s.id = ar.apriori_result
    left join public.counseling_statuses cs on cs.id = ar.counseling_status_id
    where (
      search_query is null
      or search_query = ''
      or concat_ws(' ', pd.first_name, pd.middle_name, pd.last_name, pd.name_suffix, pd.student_number) ilike '%' || search_query || '%'
    )
    and (
      selected_scenario_name is null
      or selected_scenario_name = ''
      or s.name = selected_scenario_name
    )
    and (
      selected_status_name is null
      or selected_status_name = ''
      or coalesce(cs.name, '') = selected_status_name
    )
    order by a.created_at desc
    offset ((greatest(coalesce(nullif(page_number, '')::int, 1), 1) - 1) * greatest(coalesce(nullif(page_size, '')::int, 20), 1))
    limit greatest(coalesce(nullif(page_size, '')::int, 20), 1)
  )
  select * from base;
$function$
;

-- DROP FUNCTION public.get_users_with_multiple_assessments(text, text, text, text, text);

CREATE OR REPLACE FUNCTION public.get_users_with_multiple_assessments(result_count text, selected_program_initial text, search_query text, page_size text, page_number text)
 RETURNS TABLE(total_count bigint, user_id uuid, first_name text, middle_name text, last_name text, name_suffix text, student_number text, email text, birth_date date, program_initial text, program_name text, year smallint, marital_status text, is_working_student boolean)
 LANGUAGE sql
 STABLE
AS $function$
  with assessment_counts as (
    select
      a.user_id,
      count(*)::integer as assessment_count
    from public.assessments a
    group by a.user_id
  ),
  base as (
    select
      count(*) over () as total_count,
      pd.user_id,
      pd.first_name,
      pd.middle_name,
      pd.last_name,
      pd.name_suffix,
      pd.student_number,
      pd.email,
      pd.birth_date,
      p.initial as program_initial,
      p.name as program_name,
      pd.year,
      ms.status as marital_status,
      pd.is_working_student
    from public.personal_details pd
    left join public.programs p on p.id = pd.program_id
    left join public.marital_statuses ms on ms.id = pd.marital_status_id
    left join assessment_counts ac on ac.user_id = pd.user_id
    where (
      result_count is null
      or result_count = ''
      or coalesce(ac.assessment_count, 0) = nullif(result_count, '')::int
    )
    and (
      selected_program_initial is null
      or selected_program_initial = ''
      or p.initial = selected_program_initial
    )
    and (
      search_query is null
      or search_query = ''
      or concat_ws(' ', pd.first_name, pd.middle_name, pd.last_name, pd.name_suffix, pd.student_number) ilike '%' || search_query || '%'
    )
    order by pd.first_name, pd.last_name, pd.student_number
    offset ((greatest(coalesce(nullif(page_number, '')::int, 1), 1) - 1) * greatest(coalesce(nullif(page_size, '')::int, 20), 1))
    limit greatest(coalesce(nullif(page_size, '')::int, 20), 1)
  )
  select * from base;
$function$
;

